import assert from 'node:assert/strict';
import { createServer } from 'vite';
const server = await createServer({ configFile: false, server: { middlewareMode: true }, appType: 'custom' });
try {
  const { OperationalRepository } = await server.ssrLoadModule('/frontend/src/mocks/operational.ts');
  const { fixture } = await server.ssrLoadModule('/frontend/src/domain/fixtures.ts');
  const { snapshot, periodPreset } = await server.ssrLoadModule('/frontend/src/domain/selectors.ts');
  const q = (price, unit = 'share') => ({ price, unit, currency: 'VND', date: '2026-11-03T02:00:00.000Z', source: 'Verified test provider' });
  let store = fixture(), calls = 0, result = { VN_FPT: { quote: q('50300') }, G_RING_BUY: { quote: q('13570000', 'chi') } };
  const repo = new OperationalRepository();
  const host = { get: () => store, replace: s => { store = s; }, conversation() {}, prices: async catalogs => { calls++; assert(catalogs.every(id => ['VN_FPT', 'G_RING_BUY'].includes(id))); return result; } };
  const call = (operation, input = {}, key = crypto.randomUUID(), version = store.version) => repo.dispatch({ contractVersion: '2.0.0', requestId: crypto.randomUUID(), operation, input, idempotencyKey: key, expectedWorkspaceVersion: version }, host);
  const confirm = async (id, catalogId) => {
    const h = store.holdings.find(h => h.id === id), input = { existingId: id, kind: h.kind, catalogId, quantity: h.quantity, date: h.date, cost: null, profileConfirmed: true };
    const preview = await call('previewHolding', input); await call('confirmHolding', { ...input, token: preview.data.token });
  };
  await confirm('stock', 'VN_FPT'); await confirm('gold', 'G_RING_BUY');
  const quantities = store.holdings.map(h => h.quantity), version = store.version, key = crypto.randomUUID();
  const refreshed = await call('requestPriceRefresh', { holdingIds: [] }, key);
  assert.equal(refreshed.data.status, 'succeeded'); assert.equal(calls, 1);
  assert.deepEqual(store.holdings.map(h => h.quantity), quantities); assert.equal(store.holdings[0].quotes.at(-1).price, '50300');
  assert.equal(store.holdings[1].quotes.at(-1).price, '13570000'); assert(Date.parse(store.clock) >= Date.parse(q('1').date));
  const valued = snapshot(store, periodPreset('month', store));
  assert.equal(valued.holdings[0].value, '5030000'); assert.equal(valued.holdings[1].value, '67850000');
  console.log('PASS confirmed products, current period valuation and unchanged quantities');
  const replay = await call('requestPriceRefresh', { holdingIds: [] }, key, version);
  assert.equal(replay.data.id, refreshed.data.id); assert.equal(calls, 1);
  const immediate = await call('requestPriceRefresh', { holdingIds: [] });
  assert.equal(immediate.data.status, 'succeeded'); assert.equal(immediate.data.retryAfter, null);
  assert.notEqual(immediate.data.id, refreshed.data.id); assert.equal(calls, 2);
  console.log('PASS idempotency and immediate repeat refresh without cooldown');
  const nextRefresh = async () => { repo.state.priceJobs.at(-1).requestedAt = new Date(Date.now() - 31000).toISOString(); return call('requestPriceRefresh', { holdingIds: [] }); };
  const lengths = store.holdings.map(h => h.quotes.length);
  await nextRefresh(); assert.deepEqual(store.holdings.map(h => h.quotes.length), lengths);
  result = { VN_FPT: { error: 'Upstream unavailable' }, G_RING_BUY: { quote: q('13600000', 'chi') } };
  const partial = await nextRefresh(); assert.equal(partial.data.status, 'partial'); assert.equal(store.holdings[0].quotes.at(-1).price, '50300');
  console.log('PASS duplicate observations and partial upstream failure retain last good stock price');
  result = { VN_FPT: { quote: { ...q('99999'), date: '2026-11-02T02:00:00.000Z' } }, G_RING_BUY: { quote: q('99999') } };
  const bad = await nextRefresh(); assert.equal(bad.data.status, 'failed'); assert.equal(store.holdings[0].quotes.at(-1).price, '50300'); assert.equal(store.holdings[1].quotes.at(-1).price, '13600000');
  console.log('PASS older quotes and incompatible units do not replace prices');
  store.sources.find(s => s.kind === 'price').connection = 'disconnected';
  host.prices = async ids => { assert.deepEqual(ids, []); return {}; };
  assert.equal((await nextRefresh()).data.status, 'failed');
  console.log('PASS disconnected source makes no upstream requests');
  store = fixture(); const unmapped = new OperationalRepository();
  host.prices = async ids => { assert.deepEqual(ids, []); return {}; };
  const unknown = await unmapped.dispatch({ contractVersion: '2.0.0', requestId: 'unknown', operation: 'requestPriceRefresh', input: { holdingIds: [] }, idempotencyKey: 'unknown', expectedWorkspaceVersion: store.version }, host);
  assert.equal(unknown.data.status, 'failed'); assert(unknown.data.results.every(row => /Xác nhận/.test(row.reason)));
  console.log('PASS demo assets are never silently mapped to real products');
  unmapped.state.priceJobs.at(-1).status = 'running';
  await unmapped.dispatch({ contractVersion: '2.0.0', requestId: 'read', operation: 'getState', input: {}, idempotencyKey: null, expectedWorkspaceVersion: null }, host);
  assert.equal(unmapped.state.priceJobs.at(-1).status, 'failed'); assert.equal(store.holdings[0].quotes.length, 1);
  console.log('PASS legacy queued simulation cannot publish fabricated prices');
} finally { await server.close(); }
